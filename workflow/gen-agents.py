#!/usr/bin/env python3
"""Generate ~/.claude/agents/*.md from the source agents in spiral/agents/.

Why generate rather than symlink: the sources carry `name` + `description` frontmatter ONLY,
because some skill parsers read nothing else and ignore anything richer. Claude Code needs
`tools` and `model` in frontmatter to spawn the agent. A symlink cannot add frontmatter, so an
adapter must. Per-agent config therefore lives in the source's markdown BODY:

    **model:** opus
    **tools:** Read, Grep
    ...
    ## Prompt
    ```
    <the system prompt, verbatim>
    ```

Usage: gen-agents.py <src-dir> <dest-dir> install|uninstall

install    writes dest/<name>.md for every source; skips files whose content is unchanged,
           so a re-run is a true no-op (mtimes included).
uninstall  removes only dest files carrying this script's GENERATED marker, then removes the
           directory if it is empty. A hand-authored agent is never touched.
"""
import os
import re
import sys

MARKER = "GENERATED by spiral/workflow/gen-agents.py"
NAME_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def parse_source(path):
    """-> (name, description, tools, model, prompt). Raises ValueError on anything malformed."""
    with open(path, encoding="utf-8") as fh:
        text = fh.read()

    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.S)
    if not m:
        raise ValueError(f"{path}: no YAML frontmatter")
    fm, body = m.group(1), m.group(2)

    # Frontmatter must be name + description only — the cross-harness portability rule.
    keys = re.findall(r"^([A-Za-z_][A-Za-z0-9_-]*):", fm, re.M)
    if sorted(keys) != ["description", "name"]:
        raise ValueError(f"{path}: frontmatter keys must be exactly name+description, got {keys}")

    name = re.search(r"^name:\s*(.+)$", fm, re.M).group(1).strip()
    desc = re.search(r"^description:\s*(.*)$", fm, re.M).group(1).strip()
    if not desc:  # folded block scalar: `description: >` then an indented paragraph
        blk = re.search(r"^description:\s*[>|]\s*\n((?:[ \t]+.*\n?)+)", fm, re.M)
        desc = " ".join(blk.group(1).split()) if blk else ""

    if not NAME_RE.match(name):
        raise ValueError(f"{path}: name {name!r} fails [A-Za-z0-9_-]{{1,64}}")
    if not desc:
        raise ValueError(f"{path}: empty description")
    if len(desc) > 1024:
        raise ValueError(f"{path}: description is {len(desc)} chars, max 1024")
    if name != os.path.basename(path)[: -len(".md")]:
        raise ValueError(f"{path}: name {name!r} does not match the filename")

    def field(label):
        f = re.search(rf"^\*\*{label}:\*\*\s*(.+)$", body, re.M)
        if not f:
            raise ValueError(f"{path}: body has no `**{label}:**` line")
        return f.group(1).strip()

    model = field("model")
    tools = ", ".join(t.strip() for t in field("tools").split(",") if t.strip())
    if model not in ("haiku", "sonnet", "opus", "inherit"):
        raise ValueError(f"{path}: model {model!r} is not haiku|sonnet|opus|inherit")
    if any("(" in t for t in tools.split(", ")):
        raise ValueError(f"{path}: tools takes bare tool names; permission syntax belongs in "
                         f"settings.json permissions.allow — got {tools!r}")

    p = re.search(r"^## Prompt\s*\n+```[a-z]*\n(.*?)\n```\s*$", body, re.S | re.M)
    if not p:
        raise ValueError(f"{path}: no fenced block under `## Prompt`")
    prompt = p.group(1)

    return name, desc, tools, model, prompt


def render(name, desc, tools, model, prompt, src):
    return (
        "---\n"
        f"name: {name}\n"
        f"description: {desc}\n"
        f"tools: {tools}\n"
        f"model: {model}\n"
        "---\n\n"
        f"<!-- {MARKER}\n"
        f"     from {src}\n"
        "     Do NOT hand-edit: the next install overwrites this file. Edit the source. -->\n\n"
        f"{prompt}\n"
    )


def main() -> int:
    src_dir, dest_dir, mode = sys.argv[1:4]

    if mode == "uninstall":
        removed = 0
        if os.path.isdir(dest_dir):
            for fn in sorted(os.listdir(dest_dir)):
                if not fn.endswith(".md"):
                    continue
                path = os.path.join(dest_dir, fn)
                with open(path, encoding="utf-8", errors="replace") as fh:
                    if MARKER not in fh.read():
                        continue  # hand-authored — never ours to delete
                os.remove(path)
                removed += 1
            if not os.listdir(dest_dir):
                os.rmdir(dest_dir)
        print(f"agents: removed {removed} generated file(s) from {dest_dir}")
        return 0

    if not os.path.isdir(src_dir):
        print(f"agents: no source dir {src_dir}, nothing to generate")
        return 0

    os.makedirs(dest_dir, exist_ok=True)
    written = unchanged = 0
    for fn in sorted(os.listdir(src_dir)):
        if not fn.endswith(".md") or fn == "README.md":
            continue
        src = os.path.normpath(os.path.join(src_dir, fn))
        out = render(*parse_source(src), src=src)
        dest = os.path.join(dest_dir, fn)
        if os.path.exists(dest):
            with open(dest, encoding="utf-8") as fh:
                if fh.read() == out:
                    unchanged += 1
                    continue
        with open(dest, "w", encoding="utf-8") as fh:
            fh.write(out)
        written += 1
    print(f"agents: {written} written, {unchanged} unchanged -> {dest_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
